#!/usr/bin/env python3
"""Export the approved Soft Paws CSS palette and dimensions to shared Compose."""
from pathlib import Path
import argparse
import re
import json
from design_tokens import icon_paths

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'shared/src/commonMain/kotlin/com/dracoarts/shared/presentation/theme/SoftPawsDesignTokens.kt'
ICONS = ROOT / 'shared/src/commonMain/kotlin/com/dracoarts/shared/presentation/components/SoftPawsIcons.kt'


def camel(name):
    head, *tail = name.split('-')
    return head + ''.join(word.title() for word in tail)


def generate():
    css = (ROOT / 'design/soft-paws/css/tokens.css').read_text()
    light = re.search(r':root\s*\{(.*?)\}', css, re.S).group(1)
    dark = re.search(r':root\[data-theme="dark"\]\s*\{(.*?)\}', css, re.S).group(1)
    def palette(text):
        return dict(re.findall(r'--([\w-]+):\s*#([\da-fA-F]{6})\b', text))
    palettes = [palette(light), {**palette(light), **palette(dark)}]
    roles_source = (ROOT / 'design/soft-paws/js/color-roles.js').read_text()
    roles = json.loads(roles_source.split('window.SP_COLOR_ROLES = ', 1)[1].split(';', 1)[0])
    # Compatibility names retain semantic roles while old feature components are ported.
    # All values resolve to this board; no inherited colour literal enters the app theme.
    aliases = {'glass': 'panel', 'glass-line': 'hair', 'home-ind': 'ink',
               'v3-ground': 'ground', 'ball': 'btn', 'ball-down': 'btn-down', 'ball-ink': 'btn-ink',
               'tab-bg': 'panel', 'tab-ink': 'ink', 'park-sky': 'accent-soft', 'park-sky-ink': 'ink',
               'park-hill': 'accent-soft', 'park-hill-2': 'accent-line', 'scene-hill': 'accent-soft',
               'scene-sun': 'peach', 'scene-leaf': 'accent', 'scene-shadow': 'accent-line',
               'scene-ball': 'accent', 'scene-ball-line': 'accent-line', 'dog-fur': 'peach',
               'dog-ear': 'accent', 'dog-muzzle': 'panel', 'dog-ink': 'ink', 'dog-collar': 'accent'}
    for family, tone in roles['events'].items():
        for suffix, token in {'bg': tone, 'line': f'{tone}-line', 'ink': f'{tone}-ink', 'dot': f'{tone}-ink'}.items():
            aliases[f'{family}-{suffix}'] = token
    for tone in ('good', 'bad', 'warn', 'info'):
        aliases[f'status-{tone}'] = tone
        aliases[f'status-{tone}-soft'] = f'{tone}-soft'
    result = ['// Generated by tools/soft_paws_tokens.py from design/soft-paws/css/. Do not hand-edit.',
              'package com.dracoarts.shared.presentation.theme', '',
              'import androidx.compose.ui.graphics.Color', '', 'object SoftPawsDesignTokens {']
    result += ['    val iconTones = mapOf(']
    result += [f'        "{icon}" to "{tone}",' for icon, tone in roles['icons'].items()]
    result += ['    )']
    for theme, values in zip(('Light', 'Dark'), palettes):
        result.append(f'    object {theme} {{')
        result += [f'        val {camel(key)} = Color(0xFF{value.upper()})' for key, value in values.items()]
        result += [f'        val {camel(key)} = {camel(value)}' for key, value in aliases.items()]
        result += ['        val values = mapOf(']
        result += [f'            "{key}" to {camel(key)},' for key in (*values, *aliases)]
        result += ['        )', '    }']
    styles = (ROOT / 'design/soft-paws/css/soft-paws.css').read_text()
    scroll = re.search(r'\.sp-scroll\s*\{(.*?)\}', styles, re.S).group(1)
    button = re.search(r'\.sp-btn\s*\{(.*?)\}', styles, re.S).group(1)
    padding = re.search(r'padding:\s*\d+px (\d+)px', scroll).group(1)
    control = re.search(r'min-height:\s*(\d+)px', button).group(1)
    radius = re.search(r'border-radius:\s*(\d+)px', button).group(1)
    result += [f'    const val pagePadding = {padding}', f'    const val controlHeight = {control}',
               f'    const val controlRadius = {radius}', '}', '']
    return '\n'.join(result)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'design/soft-paws/js/icons.js').read_text()
    shapes = json.loads(source.split('window.F_ICONS = ', 1)[1].split(';', 1)[0])
    for path, output in ((TARGET, generate()), (ICONS, icon_paths(shapes, 'SoftPawsIcons'))):
        if args.check:
            if not path.exists() or path.read_text() != output:
                parser.exit(1, 'Soft Paws native tokens/icons are stale. Run python3 tools/soft_paws_tokens.py.\n')
        else:
            path.write_text(output)
    if args.check:
        print('Soft Paws shared Compose palette/dimensions/icons match the approved board.')
