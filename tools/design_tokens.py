#!/usr/bin/env python3
"""Reproducible board-to-Compose export. Prints a patch; never writes app files."""
from pathlib import Path
import argparse
import json
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'shared/src/commonMain/kotlin/com/dracoarts/shared/presentation/theme/GeneratedDesignTokens.kt'
ICONS = ROOT / 'shared/src/commonMain/kotlin/com/dracoarts/shared/presentation/components/GeneratedBoardIcons.kt'
DOG = ROOT / 'shared/src/commonMain/kotlin/com/dracoarts/shared/presentation/components/GeneratedDogVector.kt'


def camel(value):
    parts = value.split('-')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def tokens():
    palettes = [{}, {}]
    for path in ['barklog-tokens.css', 'park-06.css']:
        css = (ROOT / 'design/board/css' / path).read_text()
        light = re.search(r':root\s*\{(.*?)\}', css, re.S).group(1)
        dark = re.search(r":root\[data-theme='dark'\]\s*\{(.*?)\}", css, re.S).group(1)
        for palette, text in zip(palettes, [light, dark]):
            palette.update(dict(re.findall(r'--([\w-]+):\s*#([\da-fA-F]{6})\b', text)))
    palettes[1] = {**palettes[0], **palettes[1]}
    # Component-scoped properties override inherited :root tokens even when the
    # root file is loaded later. The live character is brown, not the old orange.
    character_css = (ROOT / 'design/board/css/barklog-vibrant.css').read_text()
    character = re.search(r'\.ph\.bark\s*\{(.*?)\}', character_css, re.S).group(1)
    character_tokens = dict(re.findall(r'--(dog-[\w-]+):\s*#([\da-fA-F]{6})\b', character))
    for palette in palettes:
        palette.update(character_tokens)
    result = ['// Generated by tools/design_tokens.py from the approved board. Do not hand-edit.',
              'package com.dracoarts.shared.presentation.theme', '',
              'import androidx.compose.ui.graphics.Color', '', 'object GeneratedDesignTokens {']
    for name, values in zip(['Light', 'Dark'], palettes):
        result += [f'    object {name} {{']
        result += [f'        val {camel(key)} = Color(0xFF{value.upper()})' for key, value in values.items()]
        result += ['        val values = mapOf(' + ', '.join(f'"{key}" to {camel(key)}' for key in values) + ')']
        result += ['    }']
    motion_js = (ROOT / 'design/board/motion.tokens.js').read_text()
    motion = json.loads(motion_js.split('=', 1)[1].strip().removesuffix(';'))
    result += ['}', '', 'object BoardMotionTokens {']
    for key, value in motion.items():
        if isinstance(value, list):
            result += [f"    val {key} = floatArrayOf({', '.join(str(float(v)) + 'f' for v in value)})"]
        elif key.endswith('Ms'):
            result += [f'    const val {key} = {value}']
        else:
            result += [f'    const val {key} = {float(value)}f']
    result += ['}', '']
    return '\n'.join(result)


def icon_paths(shapes=None, object_name='GeneratedBoardIcons'):
    code = """const fs=require('fs'),vm=require('vm');
    const c={window:{F:{setReduced(){}},BARK_MOTION:{}},URLSearchParams,location:{search:''}};
    for(const p of ['design/board/js/icons.js','design/board/js/barklog.js','design/board/premium/parts.js'])vm.runInNewContext(fs.readFileSync(p,'utf8'),c);
    console.log(JSON.stringify(c.window.F_ICONS));"""
    if shapes is None:
        shapes = json.loads(subprocess.check_output(['node', '-e', code], cwd=ROOT, text=True))
    names = sorted(shapes)
    result = ['// Generated from the approved board Lucide subset. ISC notice: Lucide-LICENSE.txt.',
              'package com.dracoarts.shared.presentation.components', '',
              f'object {object_name} {{', '    val paths: Map<String, List<String>> = mapOf(']
    for name in names:
        paths = []
        for shape in shapes[name]:
            tag, attrs = shape[:2]
            if tag == 'path':
                paths.append(attrs['d'])
            elif tag == 'circle':
                x, y, r = (float(attrs[p]) for p in ['cx', 'cy', 'r'])
                paths.append(f'M{x-r},{y}a{r},{r} 0 1 0 {2*r},0a{r},{r} 0 1 0 {-2*r},0Z')
            elif tag == 'rect':
                x, y = float(attrs.get('x', 0)), float(attrs.get('y', 0))
                w, height, r = float(attrs['width']), float(attrs['height']), float(attrs.get('rx', 0))
                paths.append(f'M{x+r},{y}H{x+w-r}Q{x+w},{y} {x+w},{y+r}V{y+height-r}Q{x+w},{y+height} {x+w-r},{y+height}H{x+r}Q{x},{y+height} {x},{y+height-r}V{y+r}Q{x},{y} {x+r},{y}Z')
            elif tag == 'line':
                paths.append(f'M{attrs.get("x1", 0)},{attrs.get("y1", 0)}L{attrs.get("x2", 0)},{attrs.get("y2", 0)}')
            elif tag == 'ellipse':
                x, y, rx, ry = (float(attrs[p]) for p in ['cx', 'cy', 'rx', 'ry'])
                paths.append(f'M{x-rx},{y}a{rx},{ry} 0 1 0 {2*rx},0a{rx},{ry} 0 1 0 {-2*rx},0Z')
            elif tag in ['polyline', 'polygon']:
                paths.append('M' + attrs['points'].replace(' ', 'L') + ('Z' if tag == 'polygon' else ''))
            else:
                raise ValueError(f'Unsupported SVG shape: {name}/{tag}')
        result += [f'        "{name}" to listOf(' + ', '.join(json.dumps(p) for p in paths) + '),']
    result += ['    )', '}', '']
    return '\n'.join(result)


def dog_vector():
    code = """const fs=require('fs'),vm=require('vm');
    const F={svg:(tag,attrs,...children)=>({tag,attrs,children})};
    const c={window:{F,B:{}}};
    vm.runInNewContext(fs.readFileSync('design/board/js/dog-character.js','utf8'),c);
    console.log(JSON.stringify(c.window.B.dogCharacter()));"""
    root = json.loads(subprocess.check_output(['node', '-e', code], cwd=ROOT, text=True))
    rows = []
    def visit(node, groups=()):
        tag, a = node['tag'], node['attrs']
        if tag in ['svg', 'g']:
            group = a.get('class', '')
            for child in node['children']:
                visit(child, groups + ((group,) if tag == 'g' else ()))
            return
        if tag == 'path':
            path = a['d']
        elif tag in ['circle', 'ellipse']:
            x, y = float(a['cx']), float(a['cy'])
            rx, ry = (float(a['r']),)*2 if tag == 'circle' else (float(a['rx']), float(a['ry']))
            path = f'M{x-rx},{y}a{rx},{ry} 0 1 0 {2*rx},0a{rx},{ry} 0 1 0 {-2*rx},0Z'
        else:
            raise ValueError(tag)
        stroke = a.get('fill') == 'none'
        token = re.fullmatch(r'var\(--(.*?)\)', a['stroke' if stroke else 'fill']).group(1)
        rows.append('        DogVectorPart(' + ', '.join([
            json.dumps(path), json.dumps(token), f'{float(a.get("stroke-width", 0)) if stroke else 0.0}f',
            f'{float(a.get("opacity", 1))}f', 'listOf(' + ', '.join(json.dumps(g) for g in groups) + ')',
        ]) + '),')
    visit(root)
    return '\n'.join(['// Generated from the approved board dog-character.js. Do not hand-edit.',
        'package com.dracoarts.shared.presentation.components', '',
        'data class DogVectorPart(val path: String, val token: String, val stroke: Float, val opacity: Float, val groups: List<String>)',
        'object GeneratedDogVector {', '    val parts = listOf(', *rows, '    )', '}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--write', action='store_true', help='Regenerate the board exports in place')
    args = parser.parse_args()
    generated = [(TARGET, tokens()), (ICONS, icon_paths()), (DOG, dog_vector())]
    if args.write:
        for path, text in generated:
            path.write_text(text)
        print('Regenerated board colors, motion, icons and dog paths.')
        return
    if args.check:
        for path, text in generated:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Board export is stale: {path.relative_to(ROOT)}')
        print('Board color, motion and icon exports match.')
        return
    print('*** Begin Patch')
    for path, text in generated:
        if path.exists():
            print(f'*** Update File: {path}')
            print('@@')
            print('\n'.join('-' + line for line in path.read_text().splitlines()))
        else:
            print(f'*** Add File: {path}')
        print('\n'.join('+' + line for line in text.splitlines()))
    print('*** End Patch')


if __name__ == '__main__':
    main()
