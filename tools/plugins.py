#!/usr/bin/env python3
"""Configure app plugins and generate their shared Kotlin registration without extra dependencies."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "com.dracoarts.shared"
SOURCE = Path("shared/src/commonMain/kotlin") / Path(PACKAGE.replace(".", "/"))
MANIFEST = Path("template/plugins.json")
GENERATED = SOURCE / "services/TemplatePlugins.kt"
BUILTINS = {"auth", "analytics", "ads", "purchases", "haptics", "notifications"}
ID = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z")
CLASS = re.compile(r"(?:[a-z][a-z0-9_]*\.)+[A-Z][A-Za-z0-9]*\Z")


def load(root: Path = ROOT) -> dict:
    def unique_object(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"Duplicate JSON field: {key}")
            result[key] = value
        return result

    config = json.loads((root / MANIFEST).read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(config, dict) or set(config) != {"schemaVersion", "plugins"}:
        raise ValueError("Expected schemaVersion and plugins fields only.")
    if type(config["schemaVersion"]) is not int or config["schemaVersion"] != 1:
        raise ValueError("Unsupported plugin manifest version.")
    if not isinstance(config["plugins"], list):
        raise ValueError("plugins must be an array.")
    seen = set()
    factories = set()
    for plugin in config["plugins"]:
        if not isinstance(plugin, dict) or set(plugin) not in ({"id", "enabled"}, {"id", "enabled", "factory"}):
            raise ValueError("Each plugin needs id, enabled, and an optional factory.")
        plugin_id = plugin["id"]
        if not isinstance(plugin_id, str) or not ID.fullmatch(plugin_id) or plugin_id == "local-data":
            raise ValueError(f"Invalid or reserved plugin ID: {plugin_id!r}")
        if plugin_id in seen or type(plugin["enabled"]) is not bool:
            raise ValueError(f"Duplicate ID or non-boolean enabled value: {plugin_id}")
        seen.add(plugin_id)
        factory = plugin.get("factory")
        if plugin_id in BUILTINS:
            if factory is not None:
                raise ValueError(f"Built-in plugin {plugin_id} cannot override its factory.")
        elif not isinstance(factory, str) or not CLASS.fullmatch(factory) or factory in factories:
            raise ValueError(f"Custom plugin {plugin_id} needs a unique qualified factory class.")
        if factory:
            factories.add(factory)
    if not BUILTINS.issubset(seen):
        raise ValueError("Keep every built-in entry; use enabled=false to disable it.")
    return config


def render(config: dict) -> str:
    enabled = ", ".join(json.dumps(p["id"]) for p in config["plugins"] if p["enabled"])
    custom = [p for p in config["plugins"] if "factory" in p and p["enabled"]]
    factories = ",\n".join(f"        {p['factory']}(managers)" for p in custom)
    return f'''// Generated by tools/plugins.py. Edit template/plugins.json, then run the tool.
package {PACKAGE}.services

import {PACKAGE}.managers.AppManagers

object TemplatePlugins {{
    val enabled: Set<String> = setOf({enabled})
    fun isEnabled(id: String): Boolean = id in enabled

    @Suppress("UNUSED_PARAMETER")
    fun createModules(managers: AppManagers): List<AppModule> = listOf(
{factories}
    )
}}
'''


def synchronize(root: Path = ROOT, check: bool = False) -> None:
    expected = render(load(root))
    path = root / GENERATED
    if check:
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            raise ValueError("Plugin registration is stale. Run: python tools/plugins.py sync")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8")


def save(config: dict, root: Path = ROOT) -> None:
    (root / MANIFEST).write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    synchronize(root)


def create(plugin_id: str, root: Path = ROOT) -> None:
    if not ID.fullmatch(plugin_id) or plugin_id in BUILTINS or plugin_id == "local-data":
        raise ValueError("Use a new lowercase hyphen-separated ID, such as crash-reporting.")
    config = load(root)
    if any(p["id"] == plugin_id for p in config["plugins"]):
        raise ValueError(f"Plugin already registered: {plugin_id}")
    name = "".join(word.title() for word in plugin_id.split("-")) + "Plugin"
    factory = f"{PACKAGE}.services.plugins.{name}"
    path = root / SOURCE / f"services/plugins/{name}.kt"
    guide = root / f"docs/plugins/{plugin_id}.md"
    if path.exists() or guide.exists():
        raise ValueError("Plugin source or guide already exists; refusing to overwrite it.")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'''package {PACKAGE}.services.plugins

import {PACKAGE}.managers.AppManagers
import {PACKAGE}.services.AppModule
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow

/** Lifecycle scaffold. Add the provider implementation before enabling product behavior. */
class {name}(private val managers: AppManagers) : AppModule {{
    override val id = "{plugin_id}"
    override val priority = 50
    private val _active = MutableStateFlow(false)
    val active = _active.asStateFlow()

    override suspend fun initialize() {{
        // Acquire product resources here; propagate failure and cancellation.
        _active.value = true
    }}

    override suspend fun close() {{
        // Release any resources acquired during partial or complete initialization.
        _active.value = false
    }}
}}
''', encoding="utf-8")
    guide.parent.mkdir(parents=True, exist_ok=True)
    guide.write_text(f'''# {plugin_id}

Source: `{path.relative_to(root).as_posix()}`.

This generated lifecycle scaffold is disabled by default and has no external provider yet.
Implement the product behavior, platform adapters where required, and failure/lifecycle tests
before enabling it. Declare `dependencies` on the module if it requires another startup module.
The constructor receives the existing `AppManagers` for explicit dependency injection.

Enable with `python tools/plugins.py enable {plugin_id}`; disable with
`python tools/plugins.py disable {plugin_id}`. Both changes apply on the next build.
See [the plugin guide](../plugins.md) for lifecycle, consent, and removal behavior.
''', encoding="utf-8")
    config["plugins"].append({"id": plugin_id, "enabled": False, "factory": factory})
    save(config, root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["list", "enable", "disable", "new", "sync", "check"])
    parser.add_argument("id", nargs="?")
    args = parser.parse_args()
    if args.action in {"enable", "disable", "new"}:
        if args.id is None:
            parser.error("This action requires a plugin ID.")
    elif args.id is not None:
        parser.error("This action does not accept a plugin ID.")
    config = load()
    if args.action == "list":
        for plugin in config["plugins"]:
            print(f"{plugin['id']}: {'enabled' if plugin['enabled'] else 'disabled'}")
    elif args.action in {"enable", "disable"}:
        plugin = next((p for p in config["plugins"] if p["id"] == args.id), None)
        if plugin is None:
            raise ValueError(f"Unknown plugin: {args.id}")
        plugin["enabled"] = args.action == "enable"
        save(config)
        print(f"{args.id} {args.action}d. Rebuild the app to apply this change.")
    elif args.action == "new":
        create(args.id)
        print(f"Created {args.id}, disabled by default. Implement and test its product behavior before enabling.")
    else:
        synchronize(check=args.action == "check")
        print("Plugin registration is current.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError) as error:
        print(f"Plugin setup failed: {error}", file=sys.stderr)
        sys.exit(1)
